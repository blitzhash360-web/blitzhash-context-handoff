// Builds HANDOFF.md. The auto block is regenerated on every run; everything after it is yours and is kept.
export const AUTO_START = '<!-- context-handoff:auto:start (regenerated by `context-handoff init`; edit the sections below the end marker instead) -->';
export const AUTO_END = '<!-- context-handoff:auto:end -->';
const AUTO_START_RE = /<!-- context-handoff:auto:start[^>]*-->/;

const list = (items, empty) => (items.length ? items.join('\n') : empty);

export function renderAuto(s) {
  const out = [];
  out.push(AUTO_START, '');
  out.push(`> Generated by [context-handoff](https://github.com/blitzhash360-web/blitzhash-context-handoff). Environment variables are listed by **name only**; no values are ever written here.`, '');
  out.push('## What this is', '');
  out.push(`- **Project:** \`${s.name}\`${s.description ? ` - ${s.description}` : ''}`);
  if (s.builtWith.length) out.push(`- **Built with:** ${s.builtWith.join(', ')}`);
  if (s.packageManager) out.push(`- **Package manager:** ${s.packageManager}${s.nodeEngine ? ` (Node ${s.nodeEngine})` : ''}`);
  out.push('');

  out.push('## Stack', '');
  const byCat = new Map();
  for (const t of s.stack) { if (!byCat.has(t.category)) byCat.set(t.category, []); byCat.get(t.category).push(t.version ? `${t.label} ${t.version}` : t.label); }
  out.push(list([...byCat.entries()].map(([c, v]) => `- **${c}:** ${v.join(', ')}`), '- No known frameworks detected.'), '');

  out.push('## Commands', '');
  out.push(list(s.commands.map((c) => `- ${c.name}: \`${c.cmd}\`${c.runs ? ` (runs \`${c.runs}\`)` : ''}`), '- No scripts found.'), '');

  out.push('## Where things live', '');
  out.push(list(s.keyPaths.map((k) => `- \`${k.path}\` ${k.what} (${k.count} file${k.count === 1 ? "" : "s"})`), '- No standard folders detected.'));
  if (s.migrations) out.push(`- ${s.migrations} SQL migration file(s). Change the database with a new migration, never by editing an old one.`);
  if (s.edgeFunctions.length) out.push(`- Edge Functions: ${s.edgeFunctions.map((f) => `\`${f}\``).join(', ')}`);
  out.push('');

  out.push('## Environment variables (names only)', '');
  if (s.envVars.length) {
    out.push('| Name | Found in | In example file |', '|---|---|---|');
    for (const e of s.envVars) out.push(`| \`${e.name}\` | ${e.sources.join(', ')} | ${e.inExample ? 'yes' : s.hasEnvExample ? '**no, add it**' : '-'} |`);
    if (!s.hasEnvExample) out.push('', 'No `.env.example` found. Add one that lists these names with empty values, so the next person knows what to set.');
    const warn = s.envVars.filter((e) => e.warning);
    if (warn.length) {
      out.push('', '**Warnings**', '');
      for (const e of warn) out.push(`- \`${e.name}\`: ${e.warning} Move it to a server-only variable and rotate the key.`);
    }
  } else out.push('- None found.');
  out.push('');

  out.push('## Deploy and CI', '');
  const d = [...s.deploy.map((x) => `- ${x.label} (\`${x.file}\`)`), ...s.ci.map((f) => `- CI workflow \`${f}\``)];
  out.push(list(d, '- No deploy or CI config found.'), '');

  out.push('## Existing agent files', '');
  out.push(list(s.agentFiles.filter((f) => f !== 'HANDOFF.md').map((f) => `- \`${f}\``), '- None yet. Run `context-handoff export` to create them.'), '');

  out.push('## TODOs found in code', '');
  out.push(list(s.todos.map((t) => `- \`${t.file}:${t.line}\` ${t.tag}: ${t.text}`), '- None found.'), '');

  if (s.recent.length) out.push('## Recent changes', '', ...s.recent.map((r) => `- ${r}`), '');
  out.push(AUTO_END);
  return out.join('\n');
}

export function defaultHumanSections(s) {
  const conv = [];
  if (s.stack.some((t) => t.label === 'TypeScript')) conv.push('- TypeScript everywhere. No `any` without a comment saying why.');
  if (s.stack.some((t) => t.label === 'Zod')) conv.push('- Validate every request body and form with Zod before using it.');
  if (s.stack.some((t) => t.label === 'Tailwind CSS')) conv.push('- Style with Tailwind classes; no new CSS files unless needed.');
  if (s.stack.some((t) => t.label.startsWith('Supabase'))) conv.push('- Every table has Row Level Security on and an explicit policy. The service role key stays on the server.');
  if (s.stack.some((t) => t.label.startsWith('Stripe'))) conv.push('- Stripe webhooks verify the signature before doing anything.');
  conv.push('- Secrets come from environment variables. Never paste a key into code, chat or this file.');
  return [
    '', '## Decisions (keep this up to date)', '',
    '- _Why did you pick this stack, this auth, this host? One line each. Example: "Supabase Auth over Clerk: free tier and RLS in one place."_', '',
    '## Conventions', '', ...conv, '',
    '## Open tasks', '',
    '- [ ] _What is half-done right now? What should the next person (or agent) do first?_', '',
    '## Gotchas', '',
    '- _Anything that bit you: flaky deploys, a migration that must run by hand, a webhook that needs a tunnel locally._', '',
  ].join('\n');
}

/** Merge a fresh auto block into an existing HANDOFF.md, keeping every human-written section. */
export function buildHandoff(scan, existing) {
  const auto = renderAuto(scan);
  const title = `# Project handoff: ${scan.name}`;
  if (existing && AUTO_START_RE.test(existing) && existing.includes(AUTO_END)) {
    const before = existing.slice(0, existing.search(AUTO_START_RE));
    const after = existing.slice(existing.indexOf(AUTO_END) + AUTO_END.length);
    return before + auto + after;
  }
  if (existing && existing.trim()) {
    // A hand-written HANDOFF.md without markers: keep it all below a fresh auto block.
    return `${title}\n\n${auto}\n\n## Notes kept from your previous HANDOFF.md\n\n${existing.trim()}\n`;
  }
  return `${title}\n\nRead this first. It tells a new teammate or AI agent how this project works.\n\n${auto}\n${defaultHumanSections(scan)}`;
}

export function stripMarkers(md) {
  return md.replace(AUTO_START_RE, '').replace(AUTO_END, '').replace(/\n{3,}/g, '\n\n').trim();
}
